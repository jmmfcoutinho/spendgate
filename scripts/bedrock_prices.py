"""Generate the bundled Bedrock catalog entries from the AWS Price List bulk API (issue #105).

A maintainer tool, like `scripts/litellm_prices.py`: standard library and PyYAML only, never
imported by `spendgate` and never run by the proxy (ADR-0014, ADR-0028).

    uv run python scripts/bedrock_prices.py --download prices/           # fetch the two offers
    uv run python scripts/bedrock_prices.py --from-dir prices/ --write   # rewrite the block
    uv run python scripts/bedrock_prices.py --from-dir prices/ --check   # exit 1 on drift

Inputs:
- The AWS Price List bulk API, offers `AmazonBedrockFoundationModels` (third-party models,
  Anthropic included, priced per 1M tokens) and `AmazonBedrock` (Amazon's own models and most
  open-weight ones, priced per 1K tokens): `<dir>/<offer>/region_index.json` and
  `<dir>/<offer>/<region>.json`, as `--download` writes them.
- `scripts/bedrock_models.yaml`, the reviewed table of what the price list does not say: which
  catalog ids exist (the bare in-Region id and each inference profile, with their source
  Regions), the limits, the long-context threshold and the retirement date, all from AWS's model
  cards; and the price-list models that are left out, each with its reason.

What it writes: one block of `src/spendgate/catalog/prices.yaml` between the GENERATED markers.
Each callable model id gets entries priced from the Region the call is made from:
- a geographic profile (`eu.`, `us.`, ...) and an in-Region id at the Standard price of the
  source Region; the global profile (`global.`) at its global price;
- one region-less entry when every source Region has the same price, else one `regions:` entry
  per distinct price (ADR-0028), never a silent maximum. A source Region with no price at all
  gets no entry, so a call from there is refused (`model_not_priced`).
- cache write is the dearest cache-write price listed (the 1-hour one when there are several:
  the catalog has one cache-write meter); a long-context surcharge only where the price list
  has the long-context rows and the threshold is documented.

It fails loudly: a usage type it cannot map, a model that is in neither list of the table, a
model of the table without prices, or prices the catalog cannot express (a long-context ratio
that differs between input meters, say) stop it with exit 2 and a message naming the item.

Exit codes: 0 done (or no drift); 1 `--check` found the block differs from the data; 2 usage,
input or mapping error; 5 a download failed.
"""

