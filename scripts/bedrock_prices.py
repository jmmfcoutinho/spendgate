# --- reading the Price List --------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class Price:
    """One on-demand Standard token price of one model in one Region, per 1M tokens."""

    key: tuple[str, str, str]  # (offer, provider, model) as the price list names the model
    region: str
    meter: str  # input, output, cached_input, one of CACHE_WRITES, or FREE_WRITE
    scope: str  # "global" (global cross-Region profile) or "standard" (geographic, in-Region)
    long: bool  # the long-context row
    usd: Decimal
    effective: date


@dataclass(frozen=True, slots=True)
class Meter:
    meter: str
    scope: str
    long: bool


@dataclass(frozen=True, slots=True)
class Skip:
    reason: str


_FM_SNAKE = re.compile(
    r"(?P<m>input_tokens|output_tokens|cache_read_tokens|cached_input_tokens"
    r"|cache_write_tokens(?:_1h|_30m)?)(?P<long>_long_ctx)?_(?P<g>global_)?(?P<tier>standard|ultrafast)"
)
_FM_CAMEL = re.compile(
    r"(?P<m>InputTokenCount|OutputTokenCount|CacheReadInputTokenCount|CacheWriteInputTokenCount"
    r"|CacheWrite1hInputTokenCount)(?P<sfx>_Global|_LatencyOptimized)?"
)
_AB = re.compile(
    r"(?P<model>.+?)-(?P<m>input-tokens|output-tokens|text-input-tokens|text-output-tokens"
    r"|cache-read-input-token-count|cache-write-input-token-count)"
    r"(?P<sfx>(?:-flex|-priority|-batch|-latency-optimized|-custom-model|-cross-region-global)*)"
)
_METER = {
    "input_tokens": "input",
    "InputTokenCount": "input",
    "input-tokens": "input",
    "text-input-tokens": "input",
    "output_tokens": "output",
    "OutputTokenCount": "output",
    "output-tokens": "output",
    "text-output-tokens": "output",
    "cache_read_tokens": "cached_input",
    "cached_input_tokens": "cached_input",
    "CacheReadInputTokenCount": "cached_input",
    "cache-read-input-token-count": "cached_input",
    "cache_write_tokens": "cache_write_5m",
    "CacheWriteInputTokenCount": "cache_write_5m",
    "cache-write-input-token-count": "cache_write_5m",
    "cache_write_tokens_30m": "cache_write_30m",
    "cache_write_tokens_1h": "cache_write_1h",
    "CacheWrite1hInputTokenCount": "cache_write_1h",
}
_SKIP_SUFFIX = {
    "-flex": "Flex tier (the adapter sends no service tier, so calls are Standard)",
    "-priority": "Priority tier (the adapter sends no service tier, so calls are Standard)",
    "-batch": "batch jobs, not Converse",
    "-latency-optimized": "latency-optimized inference (the adapter never asks for it)",
    "_LatencyOptimized": "latency-optimized inference (the adapter never asks for it)",
    "-custom-model": "a custom (imported or fine-tuned) model",
}
_MODALITY = re.compile(
    r"-(?:input|output)-(?:audio|image|video)-token-count|-speech-(?:input|output)-tokens"
)


def usage_suffix(offer: str, usagetype: str) -> str:
    """The usage type without its Region code: `EU-MP:EU_input_tokens_standard-Units` -> ..."""
    if offer == "AmazonBedrockFoundationModels":
        rest = usagetype.split(":", 1)[1] if ":" in usagetype else usagetype
        return re.sub(r"^[A-Z]{2,4}\d?_", "", rest).removesuffix("-Units")
    return re.sub(r"^[A-Z]{2,4}\d?-", "", usagetype)


def classify(offer: str, usagetype: str) -> Meter | Skip | None:  # noqa: PLR0911
    """What one usage type of a mapped model prices; None if no rule knows it (an error)."""
    ut = usage_suffix(offer, usagetype)
    if offer == "AmazonBedrockFoundationModels":
        if m := _FM_SNAKE.fullmatch(ut):
            if m["tier"] == "ultrafast":
                return Skip("Ultrafast tier (the adapter never asks for it)")
            scope = "global" if m["g"] else "standard"
            return Meter(_METER[m["m"]], scope, bool(m["long"]))
        if m := _FM_CAMEL.fullmatch(ut):
            if m["sfx"] == "_LatencyOptimized":
                return Skip(_SKIP_SUFFIX["_LatencyOptimized"])
            return Meter(_METER[m["m"]], "global" if m["sfx"] else "standard", long=False)
        return None
    if "-mantle-" in ut:
        return Skip("bedrock-mantle endpoint; the adapter calls bedrock-runtime")
    if ut.endswith("-RFT-Training-Hours"):
        return Skip("fine-tuning")
    if ut.endswith("-nova-grounding"):
        return Skip("Nova web grounding requests (a system tool the adapter never sends)")
    if _MODALITY.search(ut):
        return Skip("audio, image-token or video meter; the adapter sends text and images only")
    if m := _AB.fullmatch(ut):
        sfx = m["sfx"]
        for tier, reason in _SKIP_SUFFIX.items():
            if tier in sfx:
                return Skip(reason)
        scope = "global" if "-cross-region-global" in sfx else "standard"
        return Meter(_METER[m["m"]], scope, long=False)
    return None


@dataclass(slots=True)
class Offer:
    """What was read: prices per mapped model, plus provenance and what was skipped."""

    prices: list[Price] = field(default_factory=list)
    versions: dict[str, str] = field(default_factory=dict)  # offer -> Price List version
    keys: set[tuple[str, str, str]] = field(default_factory=set)  # every model key seen
    skipped: dict[str, int] = field(default_factory=lambda: defaultdict(int))  # reason -> rows


def _read_json(path: Path) -> dict[str, Any]:
    """A JSON object from a file of at most MAX_BYTES."""
    try:
        with path.open("rb") as fh:
            raw = fh.read(MAX_BYTES + 1)
    except OSError as exc:
        raise InputError(f"cannot read {path} ({type(exc).__name__})") from None
    if len(raw) > MAX_BYTES:
        raise InputError(f"{path} is larger than {MAX_BYTES} bytes; refusing it")
    try:
        data = json.loads(raw, parse_float=Decimal)
    except ValueError as exc:
        raise InputError(f"{path} is not JSON ({exc})") from None
    if not isinstance(data, dict):
        raise InputError(f"{path} is not a JSON object")
    return data


def region_files(directory: Path, offer: str) -> list[tuple[str, Path]]:
    """The Region files the offer's region_index.json names, all of which must be present."""
    index = _read_json(directory / offer / "region_index.json")
    regions = sorted(index.get("regions", {})) if isinstance(index, dict) else []
    if not regions:
        raise InputError(f"{directory / offer / 'region_index.json'} lists no Regions")
    return [(r, directory / offer / f"{r}.json") for r in regions]


def _model_key(offer: str, attrs: Mapping[str, Any]) -> tuple[str, str, str] | None:
    model = attrs.get("model")
    if not model:
        return None
    return (offer, str(attrs.get("provider") or ""), str(model))


def _term_prices(terms: Mapping[str, Any], sku: str) -> list[tuple[str, Decimal, date]]:
    out = []
    for term in terms.get(sku, {}).values():
        effective = date.fromisoformat(str(term["effectiveDate"])[:10])
        for dim in term["priceDimensions"].values():
            out.append((str(dim["unit"]), Decimal(str(dim["pricePerUnit"]["USD"])), effective))
    return out


def read_region(
    data: Mapping[str, Any], offer: str, region: str, table: "Table", into: Offer
) -> None:
    """Every on-demand Standard token price of a mapped model in one Region file."""
    if data.get("offerCode") != offer:
        raise InputError(f"{offer}/{region}.json is offer {data.get('offerCode')!r}")
    into.versions.setdefault(offer, str(data.get("version")))
    terms = data.get("terms", {}).get("OnDemand", {})
    for sku, product in sorted(data.get("products", {}).items()):
        attrs = product.get("attributes", {})
        key = _model_key(offer, attrs)
        usagetype = str(attrs.get("usagetype", ""))
        if key is None:
            into.skipped[table.not_a_model(offer, usagetype)] += 1
            continue
        into.keys.add(key)
        if key not in table.models:
            into.skipped[table.skip_reason(key)] += 1
            continue
        feature = attrs.get("feature")
        if feature in SKIP_FEATURES:
            into.skipped[SKIP_FEATURES[str(feature)]] += 1
            continue
        if feature not in {None, "On-demand Inference"}:
            raise InputError(f"{offer} {region} {key[2]!r}: unknown feature {feature!r}")
        what = classify(offer, usagetype)
        if what is None:
            raise InputError(f"{offer} {region} {key[2]!r}: cannot map usage type {usagetype!r}")
        if isinstance(what, Skip):
            into.skipped[what.reason] += 1
            continue
        _add_prices(into, (key, region, usagetype), what, _term_prices(terms, sku))


def _add_prices(
    into: Offer,
    row: tuple[tuple[str, str, str], str, str],  # (model key, Region, usage type)
    what: Meter,
    prices: list[tuple[str, Decimal, date]],
) -> None:
    key, region, usagetype = row
    if len(prices) != 1:
        raise InputError(f"{usagetype} in {region}: {len(prices)} on-demand prices, expected one")
    unit, usd, effective = prices[0]
    if unit not in UNITS:
        raise InputError(f"{usagetype} in {region}: unit {unit!r} is not a token unit")
    if usd == 0 and what.meter in CACHE_WRITES:
        # Free cache writes (Amazon Nova) get no meter, so they bill at the input price, the
        # catalog's conservative fallback; the marker only explains that in the note. A zero
        # price anywhere else is refused.
        into.prices.append(Price(key, region, FREE_WRITE, what.scope, what.long, usd, effective))
        return
    if usd <= 0:
        raise InputError(f"{usagetype} in {region}: price {usd} is not positive")
    per_mtok = (usd * UNITS[unit]).normalize()
    into.prices.append(Price(key, region, what.meter, what.scope, what.long, per_mtok, effective))


def read_offers(directory: Path, table: "Table") -> Offer:
    out = Offer()
    for offer in OFFERS:
        for region, path in region_files(directory, offer):
            read_region(_read_json(path), offer, region, table, out)
    return out


# --- the reviewed model table ------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class Spec:
    """One price-list model and the catalog ids AWS's model card lists for it."""

    key: tuple[str, str, str]
    card: str
    model_id: str
    geo: Mapping[str, tuple[str, ...]]  # profile prefix -> its source Regions
    global_sources: tuple[str, ...]  # source Regions of the global profile
    in_region: tuple[str, ...]  # Regions where the bare id is served in-Region
    keep_bare: str | None  # why a bare id with no in-Region use stays priced
    limits: Mapping[str, int]
    long_threshold: int | None
    deprecation: str | None


@dataclass(frozen=True, slots=True)
class Table:
    models: Mapping[tuple[str, str, str], Spec]
    skip: Mapping[tuple[str, str, str], str]
    not_models: Sequence[tuple[str, re.Pattern[str], str]]  # (offer, usage-type regex, reason)

    def skip_reason(self, key: tuple[str, str, str]) -> str:
        if key not in self.skip:
            raise InputError(
                f"unmapped model {list(key)}: add it to {MODELS.name} under models or skip"
            )
        return self.skip[key]

    def not_a_model(self, offer: str, usagetype: str) -> str:
        suffix = usage_suffix(offer, usagetype)
        for where, pattern, reason in self.not_models:
            if where == offer and pattern.fullmatch(suffix):
                return reason
        raise InputError(f"{offer}: usage type {usagetype!r} names no model and no rule skips it")


def _key(raw: object, where: str) -> tuple[str, str, str]:
    if not (isinstance(raw, list) and len(raw) == 3 and raw[0] in OFFERS):  # noqa: PLR2004
        raise InputError(f"{where}: price must be [offer, provider, model], got {raw!r}")
    return (str(raw[0]), str(raw[1] or ""), str(raw[2]))


def _regions(raw: object, where: str) -> tuple[str, ...]:
    if raw is None:
        return ()
    if not isinstance(raw, list) or not all(isinstance(r, str) for r in raw):
        raise InputError(f"{where}: expected a list of Region codes")
    if len(set(raw)) != len(raw):
        raise InputError(f"{where}: a Region is listed twice")
    return tuple(sorted(raw))


def _spec(raw: Mapping[str, Any]) -> Spec:
    where = f"{MODELS.name} model {raw.get('id')!r}"
    limits = raw.get("limits") or {}
    if not isinstance(limits.get("max_output_tokens"), int):
        raise InputError(f"{where}: limits.max_output_tokens is required (from the model card)")
    lc = raw.get("long_context")
    geo = raw.get("geo") or {}
    return Spec(
        key=_key(raw.get("price"), where),
        card=str(raw["card"]),
        model_id=str(raw["id"]),
        geo={str(p): _regions(r, f"{where} geo {p}") for p, r in sorted(geo.items())},
        global_sources=_regions(raw.get("global"), f"{where} global"),
        in_region=_regions(raw.get("in_region"), f"{where} in_region"),
        keep_bare=raw.get("keep_bare"),
        limits={k: int(v) for k, v in limits.items()},
        long_threshold=int(lc["threshold_input_tokens"]) if lc else None,
        deprecation=str(raw["deprecation_date"]) if raw.get("deprecation_date") else None,
    )


def load_table(path: Path) -> Table:
    try:
        doc = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError) as exc:
        raise InputError(f"cannot read {path} ({type(exc).__name__})") from None
    models: dict[tuple[str, str, str], Spec] = {}
    for raw in doc.get("models", []):
        spec = _spec(raw)
        if spec.key in models:
            raise InputError(f"{path.name}: {list(spec.key)} is listed twice")
        models[spec.key] = spec
    skip = {
        _key(s.get("price"), f"{path.name} skip"): str(s["reason"]) for s in doc.get("skip", [])
    }
    if overlap := set(models) & set(skip):
        raise InputError(f"{path.name}: {sorted(overlap)} are both mapped and skipped")
    not_models = [
        (str(n["offer"]), re.compile(str(n["usage"])), str(n["reason"]))
        for n in doc.get("not_models", [])
    ]
    return Table(models, skip, not_models)


# --- building the entries ----------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class Priced:
    """The catalog meters one id has in one Region (hashable, so Regions can be grouped)."""

    meters: tuple[tuple[str, Decimal], ...]
    long: tuple[int, Decimal, Decimal] | None  # threshold, input and output multipliers
    effective: date
    free_write: bool = False  # AWS lists cache writes at 0; they bill at the input price here


IndexKey = tuple[tuple[str, str, str], str, str, bool]  # (model key, Region, scope, long)
Index = Mapping[IndexKey, Mapping[str, tuple[Decimal, date]]]


def index_prices(prices: Iterable[Price]) -> Index:
    out: dict[IndexKey, dict[str, tuple[Decimal, date]]] = {}
    for p in prices:
        slot = out.setdefault((p.key, p.region, p.scope, p.long), {})
        if p.meter in slot and slot[p.meter] != (p.usd, p.effective):
            raise InputError(
                f"{p.key[2]!r} {p.region} {p.scope}: two different {p.meter} prices"
                f" ({slot[p.meter][0]} and {p.usd})"
            )
        slot[p.meter] = (p.usd, p.effective)
    return out


def _catalog_meters(raw: Mapping[str, tuple[Decimal, date]], where: str) -> dict[str, Decimal]:
    if "input" not in raw or "output" not in raw:
        raise InputError(f"{where}: no input or output price ({sorted(raw)})")
    out = {"input_per_mtok": raw["input"][0]}
    if "cached_input" in raw:
        out["cached_input_per_mtok"] = raw["cached_input"][0]
    writes = [raw[w][0] for w in CACHE_WRITES if w in raw]
    if writes:
        if writes[0] != max(writes):
            raise InputError(f"{where}: the longest cache-write TTL is not the dearest")
        out["cache_write_per_mtok"] = writes[0]
    out["output_per_mtok"] = raw["output"][0]
    return out


def _long_rule(
    spec: Spec, base: Mapping[str, Decimal], long: Mapping[str, Decimal], where: str
) -> tuple[int, Decimal, Decimal]:
    if spec.long_threshold is None:
        raise InputError(f"{where}: long-context prices but no documented threshold in the table")
    if set(long) != set(base):
        raise InputError(f"{where}: long-context meters {sorted(long)} differ from {sorted(base)}")
    ratios = {m: long[m] / base[m] for m in base}
    out_ratio = ratios.pop("output_per_mtok")
    in_ratio = ratios["input_per_mtok"]
    if any(r != in_ratio for r in ratios.values()) or min(in_ratio, out_ratio) < 1:
        raise InputError(f"{where}: long-context ratios {ratios} are not one input multiplier >= 1")
    return spec.long_threshold, in_ratio.normalize(), out_ratio.normalize()


def priced(spec: Spec, idx: Index, region: str, scope: str) -> Priced | None:
    """What a call from `region` is billed at `scope`; None if the region has no such price."""
    where = f"{spec.model_id} {scope} in {region}"
    raw = idx.get((spec.key, region, scope, False))
    if not raw or "input" not in raw or "output" not in raw:
        return None  # no price, or only cache rows (a gap in AWS's data): not priced there
    meters = _catalog_meters(raw, where)
    dates = [d for _, d in raw.values()]
    long = None
    if raw_long := idx.get((spec.key, region, scope, True)):
        long = _long_rule(spec, meters, _catalog_meters(raw_long, f"{where} long"), where)
        dates += [d for _, d in raw_long.values()]
    free = FREE_WRITE in raw and "cache_write_per_mtok" not in meters
    return Priced(tuple(meters.items()), long, max(dates), free)


@dataclass(frozen=True, slots=True)
class Entry:
    model_id: str
    kind: str  # "global", "geo", "bare" or "kept": decides deployment_type and the note
    prefix: str  # profile prefix ("" for the bare id)
    regions: tuple[str, ...]  # () = region-less
    sources: tuple[str, ...]  # the source Regions this price holds for
    unpriced: tuple[str, ...]  # source Regions with no price (no entry covers them)
    price: Priced
    spec: Spec

    @property
    def catalog_id(self) -> str:
        name = f"{self.prefix}.{self.model_id}" if self.prefix else self.model_id
        return f"bedrock/{name}"


def _routes(spec: Spec, commercial: Sequence[str]) -> list[tuple[str, str, str, tuple[str, ...]]]:
    """(kind, prefix, scope, source Regions) for each catalog id of the model."""
    routes = []
    if spec.global_sources:
        routes.append(("global", "global", "global", spec.global_sources))
    routes += [("geo", p, "standard", regions) for p, regions in spec.geo.items()]
    if spec.in_region:
        routes.append(("bare", "", "standard", spec.in_region))
    elif spec.keep_bare:
        routes.append(("kept", "", "standard", tuple(commercial)))
    return routes


_ORDER = {"global": 0, "geo": 1, "bare": 2, "kept": 2}


def build_entries(table: Table, idx: Index) -> tuple[list[Entry], list[str]]:
    """The entries, and the ids a model card lists that no source Region prices."""
    regions = sorted({r for (_, r, _, _) in idx})
    commercial = [r for r in regions if not r.startswith("us-gov-")]
    keys = {k for (k, _, _, _) in idx}
    out: list[Entry] = []
    unpriced: list[str] = []
    for spec in table.models.values():
        if spec.key not in keys:
            raise InputError(f"{spec.model_id}: the price list has no price for {list(spec.key)}")
        for kind, prefix, scope, sources in _routes(spec, commercial):
            got = _entries_for(spec, idx, (kind, prefix, scope), sources)
            out += got
            if not got:
                unpriced.append(f"{prefix}.{spec.model_id}" if prefix else spec.model_id)
    out.sort(key=lambda e: (e.model_id, _ORDER[e.kind], e.prefix, e.regions))
    return out, sorted(unpriced)


def _entries_for(
    spec: Spec, idx: Index, route: tuple[str, str, str], sources: tuple[str, ...]
) -> list[Entry]:
    kind, prefix, scope = route
    groups: dict[Priced, list[str]] = defaultdict(list)
    unpriced = []
    for region in sources:
        if (p := priced(spec, idx, region, scope)) is None:
            unpriced.append(region)
        else:
            groups[p].append(region)
    if kind == "kept":  # every Region with the price; the id has no source Region of its own
        unpriced = []
    name = f"{prefix}.{spec.model_id}" if prefix else spec.model_id
    if not groups:
        return []  # the card lists the id but no source Region prices it: left out, reported
    if kind == "kept" and len(groups) > 1:
        raise InputError(f"{name}: kept bare id, but the standard price differs by Region")
    if len(groups) == 1 and not unpriced:
        ((price, regs),) = groups.items()
        return [Entry(spec.model_id, kind, prefix, (), tuple(regs), (), price, spec)]
    return [
        Entry(spec.model_id, kind, prefix, tuple(regs), tuple(regs), tuple(unpriced), price, spec)
        for price, regs in groups.items()
    ]


# --- rendering ---------------------------------------------------------------------------------

_DEPLOYMENT = {"global": "global", "geo": "data_zone", "bare": "regional", "kept": "regional"}


def dec(value: Decimal) -> str:
    """A decimal string without exponent or trailing zeros: 0.11, 4.4, 20."""
    text = format(value.normalize(), "f")
    return text.rstrip("0").rstrip(".") if "." in text else text


def _times(value: Decimal) -> str:
    return f"{dec(value)}x"


def note(entry: Entry) -> str:
    srcs = ", ".join(entry.sources)
    if entry.kind == "global":
        text = "Global cross-Region inference profile price"
        text += (
            " in these source Regions." if entry.regions else " (the same in every source Region)."
        )
    elif entry.kind == "geo":
        text = f"Geographic cross-Region profile ({entry.prefix}.); standard price"
        text += (
            " in these source Regions."
            if entry.regions
            else (f", the same in all its source Regions ({srcs}).")
        )
    elif entry.kind == "bare":
        text = "In-Region on-demand; standard price"
        text += " in these Regions." if entry.regions else f", the same in {srcs}."
    else:
        text = f"{entry.spec.keep_bare} Standard price, the same in every commercial Region."
    if entry.unpriced:
        where = "Regions" if entry.kind == "bare" else "source Regions"
        text += f" No price listed for {where} {', '.join(entry.unpriced)}: refused there."
    if entry.price.free_write:
        text += " AWS lists cache writes at 0; without a meter they bill at the input price."
    if entry.price.long:
        threshold, inp, out = entry.price.long
        rates = (
            f"{_times(inp)} all meters"
            if inp == out
            else f"{_times(inp)} input, {_times(out)} output"
        )
        text += f" Over {threshold:,} input tokens: {rates}."
    return text


def _flow(items: Iterable[tuple[str, str]]) -> str:
    return "{ " + ", ".join(f"{k}: {v}" for k, v in items) + " }"


def render_entry(entry: Entry, checked_on: str) -> list[str]:
    spec, price = entry.spec, entry.price
    lines = [
        f"  - id: {entry.catalog_id}",
        "    mode: messages",
        "    currency: USD",
        f'    effective_from: "{price.effective.isoformat()}"',
        f"    source_url: {SOURCE_URL}",
        "    verified: true",
        f'    checked_on: "{checked_on}"',
        f"    deployment_type: {_DEPLOYMENT[entry.kind]}",
    ]
    if entry.regions:
        lines.append(f"    regions: [{', '.join(entry.regions)}]")
    if spec.deprecation:
        lines.append(f'    deprecation_date: "{spec.deprecation}"')
    lines.append(f"    note: {json.dumps(note(entry))}")
    lines.append(f"    meters: {_flow((m, json.dumps(dec(v))) for m, v in price.meters)}")
    if price.long:
        threshold, inp, out = price.long
        rule = [("threshold_input_tokens", str(threshold))]
        rule += [
            ("input_multiplier", json.dumps(dec(inp))),
            ("output_multiplier", json.dumps(dec(out))),
        ]
        lines.append(f"    long_context: {_flow(rule)}")
    limits = [(k, str(spec.limits[k])) for k in _LIMITS if k in spec.limits]
    lines.append(f"    limits: {_flow(limits)}")
    return lines


_LIMITS = ("max_output_tokens", "context_window", "max_image_tokens")


def render_block(entries: Sequence[Entry], offer: Offer, checked_on: str) -> str:
    versions = ", ".join(f"{o} {offer.versions[o]}" for o in OFFERS if o in offer.versions)
    lines = [
        BEGIN,
        f"  # AWS Price List bulk API: {versions}. Ids, Regions, limits: scripts/{MODELS.name}.",
    ]
    for entry in entries:
        lines += render_entry(entry, checked_on)
    lines.append(END)
    return "\n".join(lines) + "\n"


def split_catalog(text: str) -> tuple[str, str, str]:
    """(before, block, after) around the generated block; the markers must each occur once."""
    lines = text.splitlines(keepends=True)
    begin = [i for i, line in enumerate(lines) if line.rstrip("\n") == BEGIN]
    end = [i for i, line in enumerate(lines) if line.rstrip("\n") == END]
    if len(begin) != 1 or len(end) != 1 or end[0] < begin[0]:
        raise InputError(
            f"{CATALOG.name}: expected one {BEGIN.strip()!r} ... {END.strip()!r} block"
        )
    return (
        "".join(lines[: begin[0]]),
        "".join(lines[begin[0] : end[0] + 1]),
        "".join(lines[end[0] + 1 :]),
    )


def block_checked_on(block: str) -> str | None:
    """The one checked_on date of an existing block, so --check ignores the day it runs."""
    dates = set(re.findall(r'^    checked_on: "([0-9-]+)"$', block, re.M))
    return dates.pop() if len(dates) == 1 else None


# --- downloading -------------------------------------------------------------------------------


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(  # noqa: PLR0913, PLR0917 (the stdlib's signature)
        self,
        req: urllib.request.Request,
        fp: IO[bytes],
        code: int,
        msg: str,
        headers: HTTPMessage,
        newurl: str,
    ) -> urllib.request.Request | None:
        raise DownloadError(f"the Price List answered {code} (a redirect); refusing to follow it")


def fetch(url: str) -> bytes:
    """GET an https URL on the Price List host, no redirects, at most MAX_BYTES."""
    parts = urlsplit(url)
    if parts.scheme != "https" or parts.hostname != HOST:
        raise DownloadError(f"refusing to download from {url}")
    opener = urllib.request.build_opener(_NoRedirect)
    request = urllib.request.Request(url, headers={"User-Agent": "spendgate-price-import"})  # noqa: S310
    try:
        with opener.open(request, timeout=TIMEOUT_SECONDS) as resp:
            body: bytes = resp.read(MAX_BYTES + 1)
    except (OSError, urllib.error.URLError) as exc:
        raise DownloadError(f"cannot download {url} ({type(exc).__name__})") from None
    if len(body) > MAX_BYTES:
        raise DownloadError(f"{url} is larger than {MAX_BYTES} bytes; refusing it")
    return body


def download(dest: Path, get: Callable[[str], bytes] = fetch) -> int:
    """Both offers' region_index.json and Region files into an empty `dest`; returns the count."""
    if dest.exists() and any(dest.iterdir()):
        raise InputError(f"{dest} is not empty; download into a new directory")
    count = 0
    for offer in OFFERS:
        raw = get(f"https://{HOST}/offers/v1.0/aws/{offer}/current/region_index.json")
        try:
            index = json.loads(raw)
        except ValueError:
            raise DownloadError(f"{offer}: region_index.json is not JSON") from None
        if not isinstance(index, dict):
            raise DownloadError(f"{offer}: region_index.json is not a JSON object")
        (dest / offer).mkdir(parents=True)
        for region, info in sorted(index.get("regions", {}).items()):
            path = str(info.get("currentVersionUrl", ""))
            if not re.fullmatch(
                rf"/offers/v1\.0/aws/{offer}/\d+/{re.escape(region)}/index\.json", path
            ):
                raise DownloadError(f"{offer} {region}: unexpected file path {path!r}")
            (dest / offer / f"{region}.json").write_bytes(get(f"https://{HOST}{path}"))
            count += 1
        (dest / offer / "region_index.json").write_bytes(raw)
    return count


# --- command line ------------------------------------------------------------------------------


def generate(directory: Path, table: Table, checked_on: str) -> tuple[str, str]:
    """(the block, a summary for the maintainer)."""
    offer = read_offers(directory, table)
    entries, unpriced = build_entries(table, index_prices(offer.prices))
    return render_block(entries, offer, checked_on), summary(entries, unpriced, offer)


def summary(entries: Sequence[Entry], unpriced: Sequence[str], offer: Offer) -> str:
    ids = {e.catalog_id for e in entries}
    by_prefix: dict[str, set[str]] = defaultdict(set)
    for e in entries:
        by_prefix[e.prefix or "(in-Region)"].add(e.catalog_id)
    scoped = sorted({e.catalog_id for e in entries if e.regions})
    gaps = sorted({f"{e.catalog_id} ({', '.join(e.unpriced)})" for e in entries if e.unpriced})
    lines = [
        f"{len({e.model_id for e in entries})} models, {len(ids)} ids, {len(entries)} entries"
        f" ({len(scoped)} ids priced per Region group)",
        "ids per profile: " + ", ".join(f"{p} {len(v)}" for p, v in sorted(by_prefix.items())),
        "skipped rows: " + "; ".join(f"{n} {r}" for r, n in sorted(offer.skipped.items())),
        "on a model card but priced in none of its source Regions: " + (", ".join(unpriced) or "-"),
        "source Regions without a price: " + ("; ".join(gaps) or "-"),
    ]
    return "\n".join(lines)


def _parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    what = p.add_mutually_exclusive_group(required=True)
    what.add_argument("--download", type=Path, metavar="DIR", help="fetch the Price List into DIR")
    what.add_argument("--from-dir", type=Path, metavar="DIR", help="read a downloaded Price List")
    mode = p.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="rewrite the block in the catalog")
    mode.add_argument("--check", action="store_true", help="exit 1 if the block differs")
    p.add_argument("--catalog", type=Path, default=CATALOG, help=argparse.SUPPRESS)
    p.add_argument("--models", type=Path, default=MODELS, help=argparse.SUPPRESS)
    p.add_argument("--today", default=None, help="checked_on date (default: today, UTC)")
    return p


def run(args: argparse.Namespace) -> int:
    if args.download is not None:
        count = download(args.download)
        print(f"downloaded {count} Region files into {args.download}", file=sys.stderr)
        return 0
    table = load_table(args.models)
    text = args.catalog.read_text(encoding="utf-8")
    before, current, after = split_catalog(text)
    today = args.today or datetime.now(UTC).date().isoformat()
    checked_on = (block_checked_on(current) or today) if args.check else today
    block, report = generate(args.from_dir, table, checked_on)
    print(report, file=sys.stderr)
    if args.check:
        if block != current:
            print(
                f"{args.catalog.name}: the generated Bedrock block is out of date", file=sys.stderr
            )
            return EXIT_DRIFT
        return 0
    if args.write:
        args.catalog.write_text(before + block + after, encoding="utf-8")
    else:
        sys.stdout.write(block)
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        return run(args)
    except InputError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return EXIT_INPUT
    except DownloadError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return EXIT_DOWNLOAD


if __name__ == "__main__":
    sys.exit(main())
