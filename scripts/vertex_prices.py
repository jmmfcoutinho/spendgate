"""Generate the Vertex AI prices of the Gemini models in the bundled catalog from Google's sources.

A maintainer tool (ADR-0028, point 5). It uses the standard library, PyYAML and the catalog parser
in `spendgate.core.catalog`; it is not product code and nothing in `spendgate` imports it.

    uv run python scripts/vertex_prices.py --download DIR       # needs the API key (below)
    uv run python scripts/vertex_prices.py --from-dir DIR --write   # rewrite the generated block
    uv run python scripts/vertex_prices.py --from-dir DIR --check   # exit 1 if the block drifted
    uv run python scripts/vertex_prices.py --from-dir DIR --crosscheck  # Gemini API entries

Sources, all read by `--download` into a new, empty DIR (treat it as untrusted data):

- `vertex-skus.json`: every SKU of the Vertex AI service (`C7E2-9256-1C43`) from the Cloud Billing
  API v1 (`/v1/services/<id>/skus`, paginated). It names the SKUs; its per-token prices are
  rounded to whole nanos per token (0.0825 per MTok shows as 82 nanos), so they are only a
  consistency check.
- `prices.json`: the exact price of every SKU this script maps, from the v1beta price API
  (`/v1beta/skus/<id>/price`, priced per `unitQuantity`, for example per 1,000,000 tokens).
- `gemini-api-skus.json`: the Gemini API service (`AEFD-7695-64FA`), for `--crosscheck` only.
- `locations.html`: Google's endpoint locations page. The Pricing API lists every Gemini SKU under
  the single service Region `global` and splits prices only into a global and a non-global
  ("Regional") SKU, so the Regions each model is sold in come from this page.

The key: `GOOGLE_PRICING_API_KEY` (how CI passes it), else the file named by
`GOOGLE_PRICING_API_KEY_FILE` (default `~/.config/spendgate-live/google-pricing`). It is sent in
the `X-Goog-Api-Key` header only, over a connection that refuses redirects, and never printed.

Mapping. A SKU whose description mentions Gemini is either mapped to (model, meter, endpoint, long
tier) or skipped for a listed reason; anything else stops the run (exit 2), so a new model or a
changed description is reviewed, never guessed. `FAMILIES` maps the description's model name to
the catalog model; the words after it must all be known: `Global` / `Regional` (no word: one price
for every endpoint), `Text` / `Image`, `Input` / `Output`, `Caching` (cached input), `Thinking`
(output), `Long` (the over-200K tier), plus `Predictions`, `Online`, `On`, `and`. Text and image
input share `input_per_mtok` (the dearer if they ever differ, as the adapter admits both), output
and thinking output share `output_per_mtok` (likewise). Each model gets one Region-scoped entry
per distinct price: the global SKUs price `global`, the non-global SKUs price every other Region
the locations page lists (regional and multi-region endpoints alike, as the pricing page's
"Non-global" rows say). The Gemini API keeps its region-less entries, which these never change.

Dates. `effective_from` and `checked_on` are the date of the SKUs' `effectiveTime` (the day of the
snapshot; today when the data gives none). An entry whose content is unchanged keeps the dates it
already has in the catalog, so the daily `--check` reports only real changes.

Limits, Regions not to price and lifecycle are hand-reviewed from the Vertex model pages
(https://docs.cloud.google.com/gemini-enterprise-agent-platform/models/gemini/<model>, read
2026-11-26) in `MODELS`; a model Google adds needs a row there before it is generated.

Exit codes: 0 ok; 1 `--check` found drift or `--crosscheck` a difference; 2 bad input or usage.
"""

