class InputError(ValueError):
    """The data cannot be mapped safely; the message names what, never a secret."""


class Meter(NamedTuple):
    model: str
    kind: str  # input, cached or output
    endpoint: str  # global, regional or any (no endpoint word: one price everywhere)
    long: bool


class Skip(NamedTuple):
    reason: str


def words(text: str) -> list[str]:
    return [w for w in re.sub(r"[()]", " ", text).casefold().split() if w != "-"]


def classify(description: str) -> Meter | Skip | None:
    """None for a SKU that is not about Gemini; InputError for a Gemini SKU nobody mapped."""
    text = " ".join(description.split())
    folded = text.casefold()
    if not re.search(r"\bgemini\b", folded):
        return None
    tokens = words(text)
    if hit := next((w for w in tokens if w in SKIP_WORDS), None):
        return Skip(SKIP_WORDS[hit])
    if any(a == "image" and b == "output" for a, b in pairwise(tokens)):
        return Skip("image output (image generation)")
    if hit := next((p for p in PREFIX_SKIPS if folded.startswith(p)), None):
        return Skip(PREFIX_SKIPS[hit])
    names = [f for f in (*FAMILIES, *SKIP_FAMILIES) if folded.startswith(f"gemini {f} ")]
    if not names:
        raise InputError(f"unmapped Gemini SKU {text!r}: add it to FAMILIES or a skip list")
    family = max((len(f), f) for f in names)[1]  # the longest name that matches
    if family in SKIP_FAMILIES:
        return Skip(SKIP_FAMILIES[family])
    return _meter(FAMILIES[family], words(text[len("gemini ") + len(family) :]), text)


def _meter(model: str, rest: list[str], text: str) -> Meter:
    found: dict[str, str] = {}
    flags: set[str] = set()
    for w in rest:
        slot = {
            "global": "endpoint",
            "regional": "endpoint",
            "text": "modality",
            "image": "modality",
            "input": "direction",
            "output": "direction",
        }.get(w)
        if slot is not None and slot not in found:
            found[slot] = w
        elif w in ("caching", "thinking", "long") and w not in flags:
            flags.add(w)
        elif w not in FILLER:
            raise InputError(f"unmapped word {w!r} in Gemini SKU {text!r}")
    if "modality" not in found or "direction" not in found:
        raise InputError(f"Gemini SKU {text!r} names no modality or direction")
    if found["direction"] == "output" and "caching" in flags:
        raise InputError(f"Gemini SKU {text!r} caches output")
    kind = "cached" if "caching" in flags else found["direction"]
    return Meter(model, kind, found.get("endpoint", "any"), "long" in flags)


# --- prices -------------------------------------------------------------------------------------


def money(value: Mapping[str, Any]) -> Decimal:
    if value.get("currencyCode", "USD") != "USD":
        raise InputError("a price is not in USD")
    units, nanos = int(value.get("units", 0)), int(value.get("nanos", 0))
    if units < 0 or nanos < 0 or nanos >= 10**9:
        raise InputError("a price is negative or malformed")
    return Decimal(units) + Decimal(nanos) * NANO


def per_mtok(price: Mapping[str, Any]) -> Decimal:
    """Exact USD per 1,000,000 tokens from a v1beta price: one tier from 0, a positive price."""
    rate = price.get("rate") or {}
    tiers, unit = rate.get("tiers") or [], rate.get("unitInfo") or {}
    if price.get("currencyCode") != "USD" or unit.get("unit") != "count" or len(tiers) != 1:
        raise InputError(f"{price.get('name')}: not one USD tier per token count")
    if Decimal(tiers[0].get("startAmount", {}).get("value", "0")) != 0:
        raise InputError(f"{price.get('name')}: the tier does not start at 0")
    quantity = Decimal(unit.get("unitQuantity", {}).get("value", "0"))
    listed = money(tiers[0].get("listPrice") or {})
    if quantity <= 0 or listed <= 0:
        raise InputError(f"{price.get('name')}: zero price or quantity")
    value = listed * MTOK / quantity
    if value * quantity != listed * MTOK:
        raise InputError(f"{price.get('name')}: inexact price per million tokens")
    return value


def v1_per_token(sku: Mapping[str, Any]) -> Decimal:
    """The v1 SKU's price per token (rounded to nanos by Google), for a consistency check."""
    info = sku["pricingInfo"][-1]
    expr = info["pricingExpression"]
    if expr.get("usageUnit") != "count" or expr.get("baseUnitConversionFactor", 1) != 1:
        raise InputError(f"SKU {sku['skuId']}: not priced per token count")
    if len(expr["tieredRates"]) != 1 or Decimal(info.get("currencyConversionRate", 1)) != 1:
        raise InputError(f"SKU {sku['skuId']}: not one USD tier")
    return money(expr["tieredRates"][0]["unitPrice"])


def exact_price(sku: Mapping[str, Any], prices: Mapping[str, Any]) -> Decimal:
    if sku["skuId"] not in prices:
        raise InputError(f"SKU {sku['skuId']} has no downloaded price: download again")
    value = per_mtok(prices[sku["skuId"]])
    if abs(value / MTOK - v1_per_token(sku)) >= NANO:
        raise InputError(f"SKU {sku['skuId']}: the v1 and v1beta prices disagree")
    return value


# --- Regions from the locations page ------------------------------------------------------------


class _Tables(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.tables: list[list[list[tuple[str, str]]]] = []
        self.row: list[tuple[str, str]] | None = None
        self.cell: tuple[str, list[str]] | None = None

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag == "table":
            self.tables.append([])
        elif tag == "tr" and self.tables:
            self.row = []
        elif tag in ("td", "th") and self.row is not None:
            self.cell = (dict(attrs).get("aria-label") or "", [])

    def handle_endtag(self, tag: str) -> None:
        if tag in ("td", "th") and self.row is not None and self.cell is not None:
            self.row.append((self.cell[0], " ".join("".join(self.cell[1]).split())))
            self.cell = None
        elif tag == "tr" and self.row is not None and self.tables:
            self.tables[-1].append(self.row)
            self.row = None

    def handle_data(self, data: str) -> None:
        if self.cell is not None:
            self.cell[1].append(data)


def locations(html: str) -> dict[str, set[str]]:
    """Gemini model id -> every endpoint location the page marks "Supported" for it."""
    parser = _Tables()
    parser.feed(html)
    found: dict[str, set[str]] = {}
    for table in parser.tables:
        head = [re.search(r"\(([a-z0-9-]+)\)$", text) for _, text in table[0]] if table else []
        if not any(head[1:]):
            continue
        for row in table[1:]:
            model = re.search(r"\((gemini-[a-z0-9.-]+)\)$", row[0][1]) if row else None
            if model is None:
                continue
            for (label, _), slug in zip(row[1:], head[1:], strict=False):
                if label and (label != "Supported" or slug is None):
                    raise InputError(f"unknown availability mark {label!r} on the locations page")
                if label and slug is not None:
                    found.setdefault(model.group(1), set()).add(slug.group(1))
    if not found:
        raise InputError("the locations page has no Gemini availability tables")
    return found


# --- entries ------------------------------------------------------------------------------------


def dec(value: Decimal) -> str:
    return format(value.normalize(), "f")


def collect(
    skus: Sequence[Mapping[str, Any]], prices: Mapping[str, Any]
) -> tuple[dict[str, dict[tuple[str, str, bool], Decimal]], dict[str, int]]:
    """Per model, the dearest price per (endpoint, kind, long); and the skipped SKUs per reason."""
    rates: dict[str, dict[tuple[str, str, bool], Decimal]] = {}
    skipped: dict[str, int] = {}
    for sku in skus:
        found = classify(sku["description"])
        if isinstance(found, Skip):
            skipped[found.reason] = skipped.get(found.reason, 0) + 1
        elif found is not None:
            slot = (found.endpoint, found.kind, found.long)
            price = exact_price(sku, prices)
            model = rates.setdefault(found.model, {})
            model[slot] = max(price, model.get(slot, price))
    return rates, skipped


def priced(
    model: str, rates: Mapping[tuple[str, str, bool], Decimal], endpoint: str
) -> dict[str, Any]:
    """Meters and the long-context rule of one endpoint's SKUs."""
    get = {(k, long): v for (e, k, long), v in rates.items() if e == endpoint}
    if ("input", False) not in get or ("output", False) not in get:
        raise InputError(f"{model} ({endpoint}): no input or output price")
    meters = {"input_per_mtok": get["input", False]}
    if ("cached", False) in get:
        meters["cached_input_per_mtok"] = get["cached", False]
    meters["output_per_mtok"] = get["output", False]
    out: dict[str, Any] = {"meters": {k: dec(v) for k, v in meters.items()}}
    if not any(long for _, long in get):
        return out
    if ("input", True) not in get or ("output", True) not in get:
        raise InputError(f"{model} ({endpoint}): a long-context tier without input and output")
    up_in = get["input", True] / get["input", False]
    up_out = get["output", True] / get["output", False]
    up_cached = get.get(("cached", True), meters.get("cached_input_per_mtok", 0) * up_in)
    if "cached_input_per_mtok" in meters and up_cached != meters["cached_input_per_mtok"] * up_in:
        raise InputError(f"{model} ({endpoint}): cached long-context tier is not the input's")
    if up_in < 1 or up_out < 1:
        raise InputError(f"{model} ({endpoint}): a long-context price below the base price")
    if up_in != 1 or up_out != 1:
        out["long_context"] = {
            "threshold_input_tokens": LONG_CONTEXT_THRESHOLD,
            "input_multiplier": dec(up_in),
            "output_multiplier": dec(up_out),
        }
    return out


def scopes(model: str, endpoints: set[str], listed: set[str]) -> dict[str, list[str]]:
    """Endpoint -> the Regions it prices: global SKUs `global`, non-global SKUs the rest."""
    if endpoints == {"any"}:
        return {"any": sorted(listed)}
    if "any" in endpoints:
        raise InputError(f"{model}: SKUs with and without an endpoint")
    out = {
        "global": ["global"] if "global" in listed else [],
        "regional": sorted(listed - {"global"}),
    }
    for endpoint, regions in out.items():
        if regions and endpoint not in endpoints:
            raise InputError(f"{model}: sold in {regions[0]} but no {endpoint} price")
    return {e: r for e, r in out.items() if r and e in endpoints}


def build(data: "Source", models: Mapping[str, Limits] | None = None) -> list[dict[str, Any]]:
    """Catalog entries (dates unset) for every model in `models` (`MODELS`), in a stable order."""
    models = MODELS if models is None else models
    rates, _ = collect(data.skus, data.prices)
    where = locations(data.html)
    if unknown := sorted(set(where) - set(models) - set(LOCATION_SKIPS)):
        raise InputError(f"locations page: Gemini models nobody reviewed: {unknown}")
    if missing := sorted(set(models) - set(where)):
        raise InputError(f"locations page: no longer lists {missing}")
    entries: list[dict[str, Any]] = []
    for model, limits in models.items():
        if model not in rates:
            raise InputError(f"{model}: no Vertex AI SKU found")
        entries += model_entries(model, limits, rates[model], where[model])
    return entries


def model_entries(
    model: str, limits: Limits, rates: Mapping[tuple[str, str, bool], Decimal], listed: set[str]
) -> list[dict[str, Any]]:
    """One entry per distinct price, the global one first."""
    groups: dict[str, dict[str, Any]] = {}
    for endpoint, regions in scopes(model, {e for e, _, _ in rates}, listed).items():
        body = priced(model, rates, endpoint)
        group = groups.setdefault(json.dumps(body), {"body": body, "regions": [], "kinds": []})
        group["regions"] += regions
        group["kinds"].append(endpoint)
    order = sorted((g["regions"] != ["global"], g["regions"], k) for k, g in groups.items())
    return [entry(model, limits, groups[k]) for _, _, k in order]


ENDPOINT_NOTE = {
    "global": "the global endpoint",
    "regional": "non-global endpoints (regional and multi-region)",
    "any": "every endpoint (one price)",
}


def entry(model: str, limits: Limits, group: Mapping[str, Any]) -> dict[str, Any]:
    kinds = " and ".join(ENDPOINT_NOTE[k] for k in group["kinds"])
    note = f"Vertex AI, {kinds}: Cloud Billing list price."
    if limits.deprecation_date:
        note += f" Vertex retirement date {limits.deprecation_date} (model page)."
    out: dict[str, Any] = {
        "id": f"google/{model}",
        "mode": "chat",
        "currency": "USD",
        "effective_from": None,
        "regions": sorted(group["regions"]),
        "source_url": SOURCE_URL,
        "verified": True,
        "checked_on": None,
        "note": note,
        **group["body"],
    }
    caps: dict[str, int] = {
        "max_output_tokens": limits.max_output_tokens,
        "context_window": limits.context_window,
    }
    if limits.max_image_tokens is not None:
        caps["max_image_tokens"] = limits.max_image_tokens
    out["limits"] = caps
    if limits.deprecation_date:
        out["deprecation_date"] = limits.deprecation_date
    return out


