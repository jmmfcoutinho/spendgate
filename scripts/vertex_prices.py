HEADER = f"""\
  # Vertex AI (google adapter with auth: bearer_token), generated from the Google Cloud Pricing
  # API (Cloud Billing: SKUs of service {VERTEX}, exact prices from the v1beta price API) and
  # the Regions each model is sold in from Google's endpoint locations page,
  # {LOCATIONS_URL}.
  # A Vertex deployment always has a Region (global, us, eu, europe-west4, ...), so these entries
  # price Vertex only; the region-less entries above stay the Gemini API prices. Prices are list
  # prices: Google's promotional credits ("50% credits back") are not modelled, so no hold assumes
  # them. Limits and retirement dates: the Vertex model pages, reviewed in the script's MODELS."""


def flow(values: Mapping[str, Any]) -> str:
    parts = [f'{k}: "{v}"' if isinstance(v, str) else f"{k}: {v}" for k, v in values.items()]
    return "{ " + ", ".join(parts) + " }"


def render(entries: Sequence[Mapping[str, Any]]) -> str:
    lines = [BEGIN, HEADER]
    for e in entries:
        lines += [
            f"  - id: {e['id']}",
            "    mode: chat",
            "    currency: USD",
            f'    effective_from: "{e["effective_from"]}"',
            f"    regions: [{', '.join(e['regions'])}]",
            f"    source_url: {e['source_url']}",
            "    verified: true",
            f'    checked_on: "{e["checked_on"]}"',
            f"    note: {json.dumps(e['note'])}",
            f"    meters: {flow(e['meters'])}",
        ]
        if "long_context" in e:
            lines.append(f"    long_context: {flow(e['long_context'])}")
        lines.append(f"    limits: {flow(e['limits'])}")
        if "deprecation_date" in e:
            lines.append(f'    deprecation_date: "{e["deprecation_date"]}"')
    lines.append(END)
    text = "\n".join(lines) + "\n"
    if yaml.safe_load("models:\n" + text)["models"] != [dict(e) for e in entries]:
        raise InputError("internal: the rendered block does not read back as the entries")
    return text


def split_block(text: str) -> tuple[str, str | None, str]:
    """(before, block or None, after) of the catalog text."""
    lines = text.splitlines(keepends=True)
    starts = [i for i, ln in enumerate(lines) if ln.rstrip("\n") == BEGIN]
    ends = [i for i, ln in enumerate(lines) if ln.rstrip("\n") == END]
    if not starts and not ends:
        cut = _after_gemini_api(lines)
        return "".join(lines[:cut]), None, "".join(lines[cut:])
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise InputError("the catalog's generated Vertex block markers are broken")
    s, e = starts[0], ends[0]
    return "".join(lines[:s]), "".join(lines[s : e + 1]), "".join(lines[e + 1 :])


def _after_gemini_api(lines: list[str]) -> int:
    last = max((i for i, ln in enumerate(lines) if ln.startswith("  - id: google/")), default=-1)
    if last < 0:
        raise InputError("the catalog has no google entry to place the Vertex block after")
    end = next(
        (i for i in range(last + 1, len(lines)) if not lines[i].startswith("    ")), len(lines)
    )
    return end


def dated(entries: list[dict[str, Any]], previous: str | None, day: str) -> list[dict[str, Any]]:
    """Fill in the dates: kept from an identical entry in the previous block, else the snapshot."""
    old = yaml.safe_load("models:\n" + previous)["models"] if previous else []
    out = []
    for e in entries:
        same = next((p for p in old if _undated(p) == _undated(e)), None)
        out.append(
            e
            | {
                "effective_from": same["effective_from"] if same else day,
                "checked_on": same["checked_on"] if same else day,
            }
        )
    return out


def _undated(entry: Mapping[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in entry.items() if k not in ("effective_from", "checked_on")}


# --- sources ------------------------------------------------------------------------------------


class Source(NamedTuple):
    skus: list[dict[str, Any]]
    prices: dict[str, Any]
    gemini_api: list[dict[str, Any]]
    html: str


def read_dir(path: Path) -> Source:
    try:
        load = [json.loads((path / name).read_text(encoding="utf-8")) for name in FILES[:3]]
        html = (path / FILES[3]).read_text(encoding="utf-8")
    except (OSError, ValueError) as exc:
        raise InputError(f"cannot read {path}: {type(exc).__name__}") from exc
    return Source(load[0]["skus"], load[1], load[2]["skus"], html)


def snapshot_day(skus: Sequence[Mapping[str, Any]]) -> str:
    """The SKUs' effectiveTime date (the snapshot); today (UTC) if the data gives none."""
    times = [
        p["effectiveTime"] for s in skus for p in s.get("pricingInfo", []) if p.get("effectiveTime")
    ]
    if not times:
        return datetime.now(UTC).date().isoformat()
    return max(date.fromisoformat(t[:10]) for t in times).isoformat()


# --- the Gemini API cross-check -----------------------------------------------------------------

# "Generate content input token count gemini 4 neon text", "... gemini 2.5 pro short input text".
_GEMINI_API_SKU = re.compile(
    r"^generate content (input|cached input|output) token count gemini ([a-z0-9. ]+?)"
    r"((?: short| long| input| output)*) (?:text|image)(?: non-thinking)?$"
)


def gemini_api_rates(
    skus: Sequence[Mapping[str, Any]], prices: Mapping[str, Any]
) -> dict[str, dict[str, Decimal]]:
    """The Gemini API service's plain generateContent prices: model -> meter -> dearest price."""
    meter = {
        "input": "input_per_mtok",
        "cached input": "cached_input_per_mtok",
        "output": "output_per_mtok",
    }
    out: dict[str, dict[str, Decimal]] = {}
    for sku in skus:
        hit = _GEMINI_API_SKU.match(" ".join(sku["description"].split()).casefold())
        if hit is None or "long" in hit.group(3) or sku["skuId"] not in prices:
            continue  # the long tier is a multiplier in the catalog, compared by hand
        if re.search(r"\b(contributor|experimental|preview)$", hit.group(2)):
            continue  # programme and preview SKUs, not the price list
        model = "gemini-" + hit.group(2).replace(" ", "-")
        rates = out.setdefault(model, {})
        value = per_mtok(prices[sku["skuId"]])
        rates[meter[hit.group(1)]] = max(value, rates.get(meter[hit.group(1)], value))
    return out


def crosscheck(data: Source, catalog: Mapping[str, Any], day: str) -> list[str]:
    """Differences between the Gemini API service's SKUs and our region-less google entries."""
    found = []
    for model, rates in sorted(gemini_api_rates(data.gemini_api, data.prices).items()):
        ours = [
            e
            for e in catalog["models"]
            if e["id"] == f"google/{model}" and "regions" not in e and e["effective_from"] <= day
        ]
        if not ours:
            found.append(f"google/{model}: in the Gemini API SKUs, no region-less entry in force")
            continue
        newest = max(e["effective_from"] for e in ours)
        entry = next(e for e in ours if e["effective_from"] == newest)
        for meter, value in sorted(rates.items()):
            mine = entry["meters"].get(meter)
            if mine is None or Decimal(mine) != value:
                found.append(
                    f"{entry['id']}@{entry['effective_from']} {meter}: ours {mine}, "
                    f"Gemini API SKU {dec(value)}"
                )
    return found


# --- download -----------------------------------------------------------------------------------


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *args: object, **kwargs: object) -> None:
        return None  # a keyed request never follows a redirect: the key stays with Google


def api_key() -> str:
    key = os.environ.get("GOOGLE_PRICING_API_KEY", "").strip()
    if not key:
        path = Path(os.environ.get("GOOGLE_PRICING_API_KEY_FILE") or KEY_FILE)
        try:
            key = path.read_text(encoding="utf-8").strip()
        except OSError as exc:
            raise InputError("no API key: set GOOGLE_PRICING_API_KEY or the key file") from exc
    if not re.fullmatch(r"[A-Za-z0-9_-]{20,100}", key):
        raise InputError("the API key does not look like a Google API key")
    return key


def fetch(url: str, key: str | None) -> bytes:
    headers = {"User-Agent": "spendgate-price-importer", "Accept": "application/json"}
    if not url.startswith("https://"):
        raise InputError("only https URLs are fetched")
    opener = urllib.request.build_opener(_NoRedirect) if key else urllib.request.build_opener()
    request = urllib.request.Request(  # noqa: S310 - https only, checked above
        url, headers=headers | ({"X-Goog-Api-Key": key} if key else {})
    )
    try:
        with opener.open(request, timeout=60) as response:
            body: bytes = response.read(MAX_BYTES + 1)
    except (urllib.error.URLError, TimeoutError) as exc:
        code = getattr(exc, "code", type(exc).__name__)
        raise InputError(f"download failed ({code}): {url.split('?', maxsplit=1)[0]}") from None
    if len(body) > MAX_BYTES:
        raise InputError(f"download too large: {url.split('?', maxsplit=1)[0]}")
    return body


def list_skus(service: str, key: str) -> list[dict[str, Any]]:
    skus: list[dict[str, Any]] = []
    token = ""
    for _ in range(100):
        url = f"{BILLING}/v1/services/{service}/skus?pageSize=5000"
        page = json.loads(fetch(url + (f"&pageToken={token}" if token else ""), key))
        skus += page.get("skus", [])
        if not (token := page.get("nextPageToken", "")):
            return skus
    raise InputError(f"service {service}: too many pages")


def download(target: Path) -> None:
    if target.exists() and any(target.iterdir()):
        raise InputError(f"{target} is not empty: download into a new directory")
    key = api_key()
    vertex, gemini_api = list_skus(VERTEX, key), list_skus(GEMINI_API, key)
    wanted = {s["skuId"] for s in vertex if _maps(s["description"])}
    wanted |= {
        s["skuId"]
        for s in gemini_api
        if _GEMINI_API_SKU.match(" ".join(s["description"].split()).casefold())
    }
    prices = {}
    for sku_id in sorted(wanted):
        if not re.fullmatch(r"[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{4}", sku_id):
            raise InputError("a SKU id is malformed")
        prices[sku_id] = json.loads(fetch(f"{BILLING}/v1beta/skus/{sku_id}/price", key))
    html = fetch(LOCATIONS_URL, None).decode("utf-8")
    target.mkdir(parents=True, exist_ok=True)
    for name, value in zip(
        FILES[:3], ({"skus": vertex}, prices, {"skus": gemini_api}), strict=True
    ):
        (target / name).write_text(json.dumps(value, indent=1, sort_keys=True), encoding="utf-8")
    (target / FILES[3]).write_text(html, encoding="utf-8")
    print(f"downloaded {len(vertex)} Vertex AI SKUs and {len(prices)} prices to {target}")


def _maps(description: str) -> bool:
    try:
        return isinstance(classify(description), Meter)
    except InputError:
        return False  # reported when the block is generated, with the description


# --- command line -------------------------------------------------------------------------------


def generate(
    data: Source, catalog_text: str, models: Mapping[str, Limits] | None = None
) -> tuple[str, list[dict[str, Any]], dict[str, int]]:
    """The catalog text with a fresh generated block, the entries and the skipped SKU reasons."""
    entries = build(data, models)
    before, block, after = split_block(catalog_text)
    mapped = [s for s in data.skus if _maps(s["description"])]
    entries = dated(entries, block, snapshot_day(mapped))
    rendered = render(entries)
    if block is None:
        rendered = "\n" + rendered
    text = before + rendered + after
    parse([yaml.safe_load(text)], "0" * 64, ledger_currency="USD")  # refuses anything unloadable
    return text, entries, collect(data.skus, data.prices)[1]


def main(argv: Sequence[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    p.add_argument("--from-dir", type=Path, help="read a downloaded snapshot")
    p.add_argument("--download", type=Path, metavar="DIR", help="download a snapshot into DIR")
    act = p.add_mutually_exclusive_group()
    act.add_argument("--write", action="store_true", help="rewrite the generated block")
    act.add_argument("--check", action="store_true", help="exit 1 if the block is out of date")
    act.add_argument("--crosscheck", action="store_true", help="compare the Gemini API entries")
    p.add_argument("--catalog", type=Path, default=CATALOG, help=argparse.SUPPRESS)
    args = p.parse_args(argv)
    acting = args.write or args.check or args.crosscheck
    if bool(args.from_dir) == bool(args.download) or (args.from_dir and not acting):
        p.error("give --download DIR, or --from-dir DIR with --write, --check or --crosscheck")
    try:
        if args.download:
            download(args.download)
        if not acting:
            return 0
        return run(args, read_dir(args.from_dir or args.download))
    except InputError as exc:
        print(f"vertex_prices: {exc}", file=sys.stderr)
        return 2


def run(args: argparse.Namespace, data: Source) -> int:
    current = args.catalog.read_text(encoding="utf-8")
    if args.crosscheck:
        day = snapshot_day(data.gemini_api)
        found = crosscheck(data, yaml.safe_load(current), day)
        checked = len(gemini_api_rates(data.gemini_api, data.prices))
        print("\n".join(found) if found else "no difference")
        print(f"{checked} Gemini API models compared on {day}", file=sys.stderr)
        return 1 if found else 0
    text, entries, skipped = generate(data, current)
    regions = {r for e in entries for r in e["regions"]}
    print(
        f"{len({e['id'] for e in entries})} models, {len(regions)} Regions, {len(entries)} "
        f"entries; skipped SKUs: " + ", ".join(f"{n} {r}" for r, n in sorted(skipped.items())),
        file=sys.stderr,
    )
    if args.check:
        if text == current:
            return 0
        sys.stdout.writelines(
            difflib.unified_diff(
                current.splitlines(True), text.splitlines(True), "prices.yaml", "generated", n=1
            )
        )
        return 1
    temporary = args.catalog.with_suffix(".yaml.tmp")
    temporary.write_text(text, encoding="utf-8")
    temporary.replace(args.catalog)
    return 0


if __name__ == "__main__":
    sys.exit(main())
