"""Generate the bundled Azure OpenAI catalog entries from the Azure Retail Prices API (#106).

A maintainer tool, never run by the proxy (ADR-0028, point 5). Standard library only.

    uv run python scripts/azure_prices.py --download azure.json            # fetch the price list
    uv run python scripts/azure_prices.py --from-file azure.json --write   # regenerate the block
    uv run python scripts/azure_prices.py --from-file azure.json --check   # exit 1 on drift

What it reads. Every `Foundry Models` consumption meter of the public Azure Retail Prices API
(`prices.azure.com`, no authentication). `--download` follows `NextPageLink` over https on that
host only, with no redirects and with page, size and item caps. The file is a JSON list of the
API's items (one page object is accepted too). The JSON is parsed with `parse_float=Decimal`, so
no price ever goes through a binary float.

What it writes. One block in `src/spendgate/catalog/prices.yaml`, between the `BEGIN` and `END`
lines below, right after the hand-written Azure OpenAI section. Ids name the deployment type:
`azure_openai/global.<model>`, `azure_openai/datazone.<model>` and `azure_openai/regional.<model>`
(`<model>` is Azure's model name; a version is appended when Azure prices versions apart). A
deployment type priced the same in every Region it is sold in gets one entry without `regions`.
Where Regions differ, every price gets its own `regions`-scoped entry and there is no entry
without `regions`, so a deployment in a Region Azure does not list (or without a `region`) is
refused rather than charged another Region's price. A Region that lacks a meter the model has
elsewhere (a cache-write or long-context meter, say) is left out the same way, and reported.

How meters are read. Azure's meter names are abbreviations ("gpt 4.1 nano cached Inp glbl
Tokens", "5.4 nano Inp Dz 1M Tokens"). A name is first checked against `SKIP_RULES` (variants
spendgate never imports, each with its reason), then split into words: the deployment type,
the meter (input, cached input, cache write, output, audio input), the context tier and the
model words that remain. The model words must be in `ALIASES` (imported) or `LEFT_OUT` (a
reviewed reason). Anything else, and any product that mentions OpenAI and is not listed here,
stops the run: a format change fails loudly instead of proposing a wrong price.

Limits and lifecycle come from Microsoft's pages, not the API (`MODELS`, read on `READ_ON`):
`max_output_tokens` and `context_window` from the Foundry models page, `deprecation_date` from
the model retirement schedule. Long context uses the input-token threshold OpenAI uses, which the
models page says Azure shares; the multipliers come from Azure's own long-context meters.

Exit codes: 0 done (or no drift); 1 `--check` found drift; 2 bad input, an unknown meter or a
failed download.
"""

