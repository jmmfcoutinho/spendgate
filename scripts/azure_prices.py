@dataclass(frozen=True)
class Words:
    """A meter name split into what it says."""

    model: str
    dtype: str | None
    tier: str
    cached: bool
    write: bool
    direction: str | None
    modality: str
    measure: str


@dataclass(frozen=True)
class Meter:
    """What one price-list item prices: catalog model, deployment type, meter and tier."""

    model: str
    dtype: str
    meter: str
    tier: str  # "" (no tier, or short context) or "long"


@dataclass(frozen=True)
class Skip:
    reason: str


@dataclass(frozen=True)
class Seen:
    price: Decimal  # in the catalog meter's unit
    start: date
    name: str


# --- reading meter names ---------------------------------------------------------------------


def words(name: str) -> Words:
    """Split a meter name; raise `ImportFailure` when a word category appears twice."""
    text = name.lower().replace("data zone", "datazone")
    found: dict[str, str] = {}
    flags = {"cached": False, "write": False}
    rest: list[str] = []
    for word in (w for w in re.split(r"[\s-]+", text) if w and w not in _NOISE):
        slot = _slot(word)
        if slot is None:
            rest.append(word)
        elif slot[0] in flags:
            flags[slot[0]] = True
        elif slot[0] in found and found[slot[0]] != slot[1]:
            raise ImportFailure(f"meter {name!r}: two {slot[0]} words")
        else:
            found[slot[0]] = slot[1]
    return Words(
        model=" ".join(rest),
        dtype=found.get("dtype"),
        tier=found.get("tier", ""),
        cached=flags["cached"],
        write=flags["write"],
        direction=found.get("direction"),
        modality=found.get("modality", ""),
        measure=found.get("measure", ""),
    )


def _slot(word: str) -> tuple[str, str] | None:
    tables: tuple[tuple[str, Mapping[str, str]], ...] = (
        ("dtype", _DTYPE_WORDS),
        ("tier", _TIER_WORDS),
        ("modality", _MODALITY),
        ("measure", _MEASURE),
    )
    for slot, table in tables:
        if word in table:
            return slot, table[word]
    if word in _CACHED:
        return "cached", ""
    if word == "wr":
        return "write", ""
    if word in _INPUT:
        return "direction", "in"
    if word in _OUTPUT:
        return "direction", "out"
    return None


def skip_reason(name: str) -> str | None:
    lowered = name.lower()
    for pattern, reason in SKIP_RULES:
        if re.search(pattern, lowered):
            return reason
    return None


def classify(name: str) -> Meter | Skip:
    """The catalog meter an Azure OpenAI meter name prices; `ImportFailure` if unknown."""
    if (reason := skip_reason(name)) is not None:
        return Skip(reason)
    w = words(name)
    if w.model in LEFT_OUT:
        return Skip(f"{w.model}: {LEFT_OUT[w.model]}")
    model = _BY_NAME.get(ALIASES.get(w.model, ""))
    if model is None:
        raise ImportFailure(f"unknown Azure OpenAI meter {name!r} (model words {w.model!r})")
    if w.dtype is None:
        raise ImportFailure(f"meter {name!r} names no deployment type")
    if w.dtype in model.retired_types:
        return Skip(f"{model.name} {DEPLOYMENTS[w.dtype][2]}: retired per the retirement schedule")
    meter = _meter(model, w)
    if meter is None:
        raise ImportFailure(f"meter {name!r}: cannot tell which {model.kind} meter it is")
    tier = "long" if w.tier == "long" else ""
    if tier and not model.long_context:
        raise ImportFailure(f"meter {name!r}: long context, but {model.name} has no threshold")
    return Meter(model.name, w.dtype, meter, tier)


def _meter(model: Model, w: Words) -> str | None:
    plain = not (w.cached or w.write or w.modality or w.measure)
    if model.kind == "text" and not (w.modality or w.measure):
        return _text_meter(w)
    if model.kind == "embedding" and plain and w.direction in (None, "in"):
        return "input_per_mtok"
    if model.kind == "transcribe_minutes" and w.measure == "hours" and w.direction is None:
        return "audio_input_per_minute"
    if model.kind == "speech_characters" and w.measure == "characters" and w.direction is None:
        return "per_1k_characters"
    if model.kind == "transcribe_tokens" and not (w.cached or w.write or w.measure):
        return {
            ("audio", "in"): "audio_input_per_mtok",
            ("text", "in"): "input_per_mtok",
            ("text", "out"): "output_per_mtok",
        }.get((w.modality, w.direction or ""))
    return None


def _text_meter(w: Words) -> str | None:
    if w.write:
        return "cache_write_per_mtok" if w.cached and w.direction is None else None
    if w.direction == "in":
        return "cached_input_per_mtok" if w.cached else "input_per_mtok"
    if w.direction == "out" and not w.cached:
        return "output_per_mtok"
    return None


def per_unit(meter: str, unit: str, price: Decimal, name: str) -> Decimal:
    """`price` per Azure `unit` as the catalog meter's unit (exact, or rounded up)."""
    factors = {
        ("mtok", "1M"): Decimal(1),
        ("mtok", "1K"): Decimal(1000),
        ("chars", "1M"): Decimal("0.001"),
        ("chars", "1K"): Decimal(1),
        ("minute", "1 Hour"): Decimal(1) / Decimal(60),
    }
    family = "minute" if meter.endswith("minute") else "chars" if "char" in meter else "mtok"
    factor = factors.get((family, unit))
    if factor is None:
        raise ImportFailure(f"meter {name!r}: unit {unit!r} does not fit {meter}")
    if family != "minute":
        return price * factor
    with localcontext() as ctx:  # per hour to per minute: round up at 12 places, never down
        ctx.prec = 50
        return (price / 60).quantize(Decimal("1e-12"), rounding=ROUND_CEILING)


